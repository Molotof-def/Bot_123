/** Return a quote biased toward harsher tiers when balance is low */
export function getQuote(balance: number): string {
  let tier: number;
  if (balance > 500_000) tier = 0;
  else if (balance > 50_000) tier = 1;
  else if (balance > 5_000) tier = 2;
  else tier = 3;
  const slice = FUNNY_SUPPORT_QUOTES.slice(tier * 50, tier * 50 + 50);
  return slice[Math.floor(Math.random() * slice.length)];
}
